/**
 * gen-world-dots — offline generator for the CyberShield "Global Signal Field".
 *
 * Reads the NASA equirectangular land/ocean raster (land_shallow_topo_2048.jpg),
 * downsamples it to a COLS×ROWS grid, classifies water vs land per cell
 * (ocean pixels are blue-dominant), and emits the land mask as a base64
 * bit-mask into src/lib/cyber/world-dots.ts.
 *
 * Run: bun scripts/gen-world-dots.ts /tmp/land.jpg
 */
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const COLS = 216; // ~1.667° per cell
const ROWS = 108;

const input = process.argv[2] ?? "/tmp/land.jpg";

const { data, info } = await sharp(input)
  .resize(COLS, ROWS, { fit: "fill" })
  .raw()
  .toBuffer({ resolveWithObject: true });

const bits: number[] = [];
let landCount = 0;
for (let y = 0; y < ROWS; y++) {
  for (let x = 0; x < COLS; x++) {
    const i = (y * COLS + x) * info.channels;
    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];
    // ocean: blue clearly dominates red; ice/clouds are neutral white → land side
    const isLand = !(b > r + 8 && b > g + 2);
    if (isLand) landCount++;
    bits.push(isLand ? 1 : 0);
  }
}

// pack bits MSB-first into bytes, then base64
const bytes = new Uint8Array(Math.ceil(bits.length / 8));
for (let i = 0; i < bits.length; i++) {
  if (bits[i]) bytes[i >> 3] |= 0x80 >> (i & 7);
}
const b64 = Buffer.from(bytes).toString("base64");

const clean = `// AUTO-GENERATED by scripts/gen-world-dots.ts — do not edit by hand.
// Source: NASA "Land Surface, Ocean Color and Sea Ice" equirectangular raster
// (${COLS}×${ROWS} cells, ${landCount} land cells). Base64-packed row-major bitmask,
// MSB first, 1 = land cell. Used by the Global Signal Field WebGL backdrop.

export const MAP_COLS = ${COLS};
export const MAP_ROWS = ${ROWS};
export const LAND_MASK_B64 = "${b64}";

export interface MapDot {
  /** world x on a [-0.5, 0.5] unit plane */
  x: number;
  /** world y on a [-0.5, 0.5] unit plane (north positive) */
  y: number;
  lon: number;
  lat: number;
}

/** Decode the bitmask into unit-plane dot coordinates. */
export function decodeMapDots(): MapDot[] {
  const bin =
    typeof atob === "function"
      ? atob(LAND_MASK_B64)
      : Buffer.from(LAND_MASK_B64, "base64").toString("binary");
  const dots: MapDot[] = [];
  for (let row = 0; row < MAP_ROWS; row++) {
    for (let col = 0; col < MAP_COLS; col++) {
      const idx = row * MAP_COLS + col;
      const byte = bin.charCodeAt(idx >> 3);
      if ((byte & (0x80 >> (idx & 7))) === 0) continue;
      dots.push({
        x: col / (MAP_COLS - 1) - 0.5,
        y: 0.5 - row / (MAP_ROWS - 1),
        lon: (col / (MAP_COLS - 1)) * 360 - 180,
        lat: 90 - (row / (MAP_ROWS - 1)) * 180,
      });
    }
  }
  return dots;
}

/** lon/lat → unit plane coords (equirectangular, matches decodeMapDots). */
export function lonLatToPlane(lon: number, lat: number): { x: number; y: number } {
  return {
    x: (lon + 180) / 360 - 0.5,
    y: 0.5 - (lat + 90) / 180,
  };
}
`;

writeFileSync("src/lib/cyber/world-dots.ts", clean);
console.log(`world-dots.ts written: ${landCount}/${COLS * ROWS} land cells, ${b64.length} b64 chars`);
